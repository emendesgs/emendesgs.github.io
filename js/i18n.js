/**
 * Aplica o idioma escolhido no DOM
 * @param {'pt' | 'en'} lang 
 */
function setLanguage(lang) {
    if (!I18N[lang]) lang = 'pt';
    
    // Atualiza o atributo lang do HTML
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';

    // Salva preferência no LocalStorage
    localStorage.setItem('em_portfolio_lang', lang);

    const dict = I18N[lang];

    // Atualiza nós com data-i18n (texto puro)
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            el.textContent = dict[key];
        }
    });

    // Atualiza nós com data-i18n-html (contém tags <strong>, etc)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    // Atualiza links com data-i18n-href (ex: alternar PDF do CV PT/EN)
    document.querySelectorAll('[data-i18n-href]').forEach(el => {
        const key = el.getAttribute('data-i18n-href');
        if (dict[key] !== undefined) {
            el.setAttribute('href', dict[key]);
        }
    });

    // Atualiza atributo download com data-i18n-download
    document.querySelectorAll('[data-i18n-download]').forEach(el => {
        const key = el.getAttribute('data-i18n-download');
        if (dict[key] !== undefined) {
            el.setAttribute('download', dict[key]);
        }
    });

    // Atualiza botões do switcher
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-set-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });
}

// Inicialização: Lê LocalStorage ou define 'pt' como padrão obrigatório
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('em_portfolio_lang') || 'pt';
    setLanguage(savedLang);

    // Event listener nos botões de troca de idioma
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const targetLang = e.currentTarget.getAttribute('data-set-lang');
            if (targetLang) {
                setLanguage(targetLang);
            }
        });
    });
});
